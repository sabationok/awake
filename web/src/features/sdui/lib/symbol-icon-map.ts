/** SF Symbol з дерева → іконка lucide. Невідома назва малює крапку-заглушку. */
const SYMBOL_ICON: Record<string, LucideIcon | undefined> = {
  'cup.and.saucer.fill': Coffee,
  'waveform.path.ecg': Activity,
  'list.bullet.rectangle': ScrollText,
  'gearshape.fill': Settings,
  'battery.75': BatteryMedium,
  'battery.25': BatteryLow,
  'battery.0': BatteryWarning,
  'chart.bar.xaxis': ChartColumn,
  'clock.arrow.circlepath': History,
  display: Monitor,
  'shield.fill': Shield,
  'slider.horizontal.3': SlidersHorizontal,
  'flame.fill': Flame,
  'powerplug.fill': Plug,
  'thermometer.medium': Thermometer,
  laptopcomputer: Laptop,
  wifi: Wifi,
  'lock.laptopcomputer': LaptopMinimal,
  'paperplane.fill': Send,
  'moon.fill': Moon,
  'moon.zzz.fill': Moon,
  'speaker.wave.2.fill': Volume2,
  'speaker.slash.fill': VolumeX,
  'sun.max.fill': Sun,
  lock: Lock,
  'xmark.circle': CircleX,
  'hand.raised': Hand,
  trash: Trash2,
  'doc.on.doc': Copy,
  pencil: Pencil,
  bell: Bell,
  'exclamationmark.triangle': TriangleAlert,
  'info.circle': Info,
  'rectangle.portrait.and.arrow.right': LogOut,
  plus: Plus,
  power: Power,
};

/** Іконка lucide за SF Symbol; невідома назва — undefined (для меню без іконки). */
export function findSymbolIcon(symbol: string): LucideIcon | undefined {
  return SYMBOL_ICON[symbol];
}

export function resolveSymbolIcon(symbol: string): LucideIcon {
  return findSymbolIcon(symbol) ?? Circle;
}
